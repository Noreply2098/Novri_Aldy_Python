# iterasi data list
messeges = ["morning", "afternoon", "evening"]
for m in messeges:
    print(m)

# iterasi data tuple
numbers = ("twenty four", 24)
for n in numbers:
    print(n)

# iterasi data string
for char in "hellow pityon":
    print(char)

# iterasi data dictionary 
bio = {
    "name": "porche",
    "year": 1778,
}

for key in bio:
    print("key:", key, "value:", bio[key])



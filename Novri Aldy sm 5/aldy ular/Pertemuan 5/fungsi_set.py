# konversi string ke set
data = set('bacdefg')
print(data)

# konversi list ke set
data2 = set(['a', 'b', 'c', 'd', 'e'])
print('data2', data2)

# konversi tuple ke set
data3 = set(('a', 'b', 'c', 'd', 'e'))
print('data3', data3)

# konversi range ke set
data4 = set(range(1, 5))
print('data4', data4)